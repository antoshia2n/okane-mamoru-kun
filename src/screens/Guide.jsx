export default function Guide() {
  return (
    <div style={{ display: "grid", gap: 12, gridTemplateColumns: "minmax(0,1fr)" }}>
      {GUIDE.map((s) => (
        <Box key={s.title} title={s.title}>
          {s.blocks.map((b, i) => <Block key={i} kind={b[0]} value={b[1]} />)}
        </Box>
      ))}
    </div>
  );
}

/** **で囲んだところを太字にする */
function rich(text) {
  return String(text).split("**").map((x, i) => (i % 2 ? <b key={i}>{x}</b> : x)).filter((x) => x !== "");
}

function Block({ kind, value }) {
  if (kind === "p")  return <p style={p}>{rich(value)}</p>;
  if (kind === "pm") return <p style={{ ...p, color: T.muted }}>{rich(value)}</p>;
  if (kind === "ol") return <ol style={ol}>{value.map((v, i) => <li key={i}>{rich(v)}</li>)}</ol>;
  if (kind === "ul") return <ul style={ul}>{value.map((v, i) => <li key={i}>{rich(v)}</li>)}</ul>;
  if (kind === "note") return <div style={note}>{rich(value)}</div>;
  if (kind === "table") return (
    <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 12 }}>
      <tbody>{value.map(([a, b]) => <Row key={a} a={a} b={b} />)}</tbody>
    </table>
  );
  return null;
}

function Box({ title, children }) {
  return (
    <div style={{ ...card, padding: "14px 16px" }}>
      <div style={{ ...lb10, marginBottom: 8 }}>{title}</div>
      {children}
    </div>
  );
}

function Row({ a, b }) {
  return (
    <tr style={{ borderTop: `1px solid ${T.border}` }}>
      <td style={{ padding: "6px", fontWeight: 700, whiteSpace: "nowrap" }}>{a}</td>
      <td style={{ padding: "6px", color: T.muted }}>{b}</td>
    </tr>
  );
}

const p  = { fontSize: 12.5, lineHeight: 1.85, marginBottom: 6 };
const ol = { fontSize: 12.5, lineHeight: 2, paddingLeft: 20 };
const ul = { fontSize: 12.5, lineHeight: 1.95, paddingLeft: 18 };
const note = {
  marginTop: 10, background: "#FAF4EA", border: `1px solid ${T.amber}`,
  borderRadius: 8, padding: "10px 12px", fontSize: 12, lineHeight: 1.8,
};
